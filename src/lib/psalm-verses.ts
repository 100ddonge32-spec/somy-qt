export function getRandomPsalm(): PsalmQT {
    const randomIndex = Math.floor(Math.random() * PSALM_VERSES.length);
    return PSALM_VERSES[randomIndex];
}

export function getDailyPsalm(): PsalmQT {
    const now = new Date(Date.now() + 9 * 60 * 60 * 1000);
    const startOfYear = new Date(now.getFullYear(), 0, 1);
    const dayOfYear = Math.floor((now.getTime() - startOfYear.getTime()) / (24 * 60 * 60 * 1000));
    const index = Math.max(0, dayOfYear) % PSALM_VERSES.length;
    return PSALM_VERSES[index];
}
